-- Reconstructed from the deployed schema on project dkafqgapepebzjtoghos.
--
-- This migration was applied straight to the remote database without a file in
-- the repo, which made `supabase db push` fail with "Remote migration versions
-- not found in local migrations directory". This reproduces the deployed shape
-- so local and remote agree.
--
-- environmental_snapshots stores the conditions sampled for a spot at a point in
-- time and backs the /api/spots/[id]/conditions history view. Additive and safe to
-- run more than once.

CREATE TABLE IF NOT EXISTS public.environmental_snapshots (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  spot_id uuid NOT NULL REFERENCES public.spots(id) ON DELETE CASCADE,
  captured_at timestamptz NOT NULL DEFAULT now(),
  air_temp_c numeric,
  wind_speed_ms numeric,
  water_temp_c numeric,
  water_level_m numeric,
  flow_rate_cfs numeric,
  dissolved_oxygen_mgl numeric,
  fishing_score numeric,
  raw_data jsonb
);

-- Newest-first reads per spot are the only access pattern the API uses.
CREATE INDEX IF NOT EXISTS environmental_snapshots_spot_captured_at_idx
  ON public.environmental_snapshots (spot_id, captured_at DESC);

ALTER TABLE public.environmental_snapshots ENABLE ROW LEVEL SECURITY;

-- Reads go through the service role from server routes; no anon/authenticated
-- SELECT grant is issued, so no public policy is needed here.
GRANT SELECT, INSERT, UPDATE, DELETE ON public.environmental_snapshots TO service_role;
