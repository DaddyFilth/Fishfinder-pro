--
-- spot_ai_predictions holds one scored prediction per spot per day, written by the
-- scheduled analysis job and read publicly by the map/spot panels. Additive and
-- safe to run more than once.

CREATE TABLE IF NOT EXISTS public.spot_ai_predictions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  spot_id uuid NOT NULL REFERENCES public.spots(id) ON DELETE CASCADE,
  prediction_date date NOT NULL DEFAULT CURRENT_DATE,
  model text NOT NULL,
  fishing_score integer NOT NULL,
  rating text NOT NULL,
  primary_species jsonb NOT NULL DEFAULT '[]'::jsonb,
  best_time_today text NOT NULL,
  best_technique text NOT NULL,
  recommended_lure text NOT NULL,
  reason text NOT NULL,
  evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
  generated_at timestamptz NOT NULL DEFAULT now()
);

-- One prediction per spot per day; the job upserts on this key.
CREATE UNIQUE INDEX IF NOT EXISTS spot_ai_predictions_spot_id_prediction_date_key
  ON public.spot_ai_predictions (spot_id, prediction_date);

-- Feeds the "top spots today" style ranked listings.
CREATE INDEX IF NOT EXISTS spot_ai_predictions_date_idx
  ON public.spot_ai_predictions (prediction_date, fishing_score DESC);

ALTER TABLE public.spot_ai_predictions ENABLE ROW LEVEL SECURITY;

-- Predictions are not sensitive and are surfaced to signed-out visitors, which is
-- why anon/authenticated hold SELECT and the policy is permissive.
GRANT SELECT ON public.spot_ai_predictions TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.spot_ai_predictions TO service_role;

DROP POLICY IF EXISTS spot_ai_predictions_read_public ON public.spot_ai_predictions;
CREATE POLICY spot_ai_predictions_read_public
  ON public.spot_ai_predictions
  FOR SELECT
  TO public
  USING (true);
